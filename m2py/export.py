"""Translate every matlab/core/*.m into a Python module (noisebox/core_py/<name>.py).

Usage (normally started by matlab/nb_export_python.m):
    python -I m2py/export.py --core matlab/core --out noisebox/core_py [--overrides matlab/python_overrides]
                             [--require a,b,c] [--json result.json]

Nothing is guessed: a construct the translator does not know stops THAT file with the .m file and line number.
A file that fails is reported and left out; if a REQUIRED function (one the ArcGIS tools call) fails, the exit
code is 2 and the previous generated package is kept untouched.
"""
import argparse
import datetime
import hashlib
import json
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

from m2py.codegen import ModuleGen, UnsupportedError          # noqa: E402
from m2py.mparser import MParseError, parse                    # noqa: E402


def md5(path):
    """md5 of a text file with Windows/Unix line endings treated alike (so git's line-ending conversion is harmless)."""
    with open(path, "rb") as f:
        return hashlib.md5(f.read().replace(b"\r\n", b"\n")).hexdigest()


def read_text(path):
    with open(path, "rb") as f:
        raw = f.read()
    for enc in ("utf-8", "cp1252"):
        try:
            return raw.decode(enc)
        except UnicodeDecodeError:
            continue
    return raw.decode("utf-8", errors="replace")


def norm_md5(path):
    """md5 of a text file with Windows/Unix line endings treated alike (for the accelerator guard)."""
    with open(path, "rb") as f:
        raw = f.read().replace(b"\r\n", b"\n")
    return hashlib.md5(raw).hexdigest()


ACCEL_RE = re.compile(r"^# MATLAB-MD5: (\S+)", re.M)


def stamp_accelerators(core_dir, accel_dir):
    """Developer tool: record the CURRENT md5 of each .m file in its accelerator (do this only after the
    accelerator has been checked against MATLAB by nb_export_python)."""
    for f in sorted(os.listdir(accel_dir)):
        if not f.endswith(".py"):
            continue
        m = os.path.join(core_dir, f[:-3] + ".m")
        if not os.path.isfile(m):
            print("no .m file for accelerator", f)
            continue
        txt = read_text(os.path.join(accel_dir, f))
        new = ACCEL_RE.sub("# MATLAB-MD5: " + norm_md5(m), txt, count=1)
        with open(os.path.join(accel_dir, f), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(new)
        print("stamped", f)


def _builtin_check(n):
    from noisebox import mrt
    return hasattr(mrt, "b_" + n)


def translate_all(core_dir, overrides_dir=None, accel_dir=None):
    """-> (modules {name: source}, info {name: dict}, failed {name: reason}); notes in info["_notes"]"""
    files = sorted(f for f in os.listdir(core_dir) if f.lower().endswith(".m"))
    parsed, failed, info = {}, {}, {}
    texts = {}
    for f in files:
        name = f[:-2]
        path = os.path.join(core_dir, f)
        text = read_text(path)
        texts[name] = text
        try:
            funcs = parse(text)
            if funcs[0]["name"] != name:
                raise MParseError("the first function is '%s' but the file is called '%s.m' (MATLAB uses the "
                                  "file name)" % (funcs[0]["name"], name), funcs[0]["line"])
            parsed[name] = funcs
            info[name] = {"file": f, "md5": md5(path), "params": funcs[0]["params"], "outs": funcs[0]["outs"],
                          "line_count": text.count("\n") + 1}
        except MParseError as e:
            failed[name] = "%s.m: %s" % (name, e)
            info[name] = {"file": f, "md5": md5(path), "params": [], "outs": []}
    overrides = {}
    if overrides_dir and os.path.isdir(overrides_dir):
        for f in os.listdir(overrides_dir):
            if f.endswith(".py") and not f.startswith("_"):
                overrides[f[:-3]] = os.path.join(overrides_dir, f)
    public = set(parsed) | set(overrides)
    modules = {}
    changed = True
    while changed:
        changed = False
        for name, funcs in list(parsed.items()):
            if name in overrides:
                continue
            try:
                mg = ModuleGen(name, [dict(fn) for fn in funcs], texts[name].splitlines(), public, _builtin_check)
                header = ("# GENERATED by m2py from matlab/core/%s.m (md5 %s) on %s.\n"
                          "# DO NOT EDIT this file: change the .m file and run matlab/nb_export_python.m.\n"
                          "# flake8: noqa\n" % (name, info[name]["md5"], datetime.date.today().isoformat()))
                modules[name] = mg.generate(header)
            except UnsupportedError as e:
                failed[name] = "%s.m: %s" % (name, e)
                public.discard(name)
                parsed.pop(name)
                modules.pop(name, None)
                changed = True
                break
            except Exception as e:                                         # translator bug: say where
                failed[name] = "%s.m: internal translator error %s: %s" % (name, type(e).__name__, e)
                public.discard(name)
                parsed.pop(name)
                modules.pop(name, None)
                changed = True
                break
    notes = []
    if accel_dir and os.path.isdir(accel_dir):
        for f in sorted(os.listdir(accel_dir)):
            if not f.endswith(".py") or f.startswith("_"):
                continue
            name = f[:-3]
            mpath = os.path.join(core_dir, name + ".m")
            if name not in modules or not os.path.isfile(mpath):
                continue
            src = read_text(os.path.join(accel_dir, f))
            m = ACCEL_RE.search(src)
            if m and m.group(1) == norm_md5(mpath):
                modules[name] = ("# ACCELERATED version of matlab/core/%s.m (hand-optimised Python kept in "
                                 "matlab/python_accel/).\n# It is only used while the .m file is unchanged, and "
                                 "nb_export_python compares it with MATLAB.\n# flake8: noqa\n" % name) + src
                info[name]["accelerated"] = True
            else:
                notes.append("%s.m was edited: its accelerator is NOT used (the generated version is slower but "
                             "follows your MATLAB code exactly)." % name)
    info["_notes"] = notes
    for name, path in overrides.items():
        if name in texts:
            modules[name] = ("# HAND-WRITTEN override of matlab/core/%s.m (kept in matlab/python_overrides/).\n"
                             "# flake8: noqa\n" % name) + read_text(path)
            info.setdefault(name, {"file": name + ".m", "md5": "", "params": [], "outs": []})["override"] = True
            failed.pop(name, None)
    return modules, info, failed


INIT_SRC = '''"""Python translation of the MATLAB core (generated by m2py; do not edit).

Every function of matlab/core/*.m is available here under the same name and with the same inputs and outputs:
    from noisebox import core_py
    core_py.load()
    core_py.nb_adiv(100.0)

`load()` imports the modules and wires them together; `reload()` picks up a newly generated version.
See manifest.json for the list of functions with their inputs and outputs.
"""
import importlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FUNCTIONS = %(functions)r


def manifest():
    with open(os.path.join(HERE, "manifest.json"), "r", encoding="utf-8") as f:
        return json.load(f)


def _wire(mods):
    ns = {}
    for name, m in mods.items():
        ns[name] = getattr(m, name)
    for m in mods.values():
        m.__dict__.update(ns)
    globals().update(ns)
    return ns


def load(reload=False):
    mods = {}
    for name in FUNCTIONS:
        full = __name__ + "." + name
        if reload and full in sys.modules:
            mods[name] = importlib.reload(sys.modules[full])
        else:
            mods[name] = importlib.import_module(full)
    return _wire(mods)


def reload():
    importlib.invalidate_caches()
    return load(reload=True)
'''


def write_package(out_dir, modules, info, failed, core_dir, required):
    tmp = out_dir + ".new"
    if os.path.isdir(tmp):
        shutil.rmtree(tmp)
    os.makedirs(tmp)
    for name, src in modules.items():
        with open(os.path.join(tmp, name + ".py"), "w", encoding="utf-8", newline="\n") as f:
            f.write(src if src.endswith("\n") else src + "\n")
    names = sorted(modules)
    with open(os.path.join(tmp, "__init__.py"), "w", encoding="utf-8", newline="\n") as f:
        f.write(INIT_SRC % {"functions": names})
    notes = list(info.get("_notes", []))
    man = {
        "generated": datetime.datetime.now().isoformat(timespec="seconds"),
        "notes": notes,
        "matlab_core": os.path.abspath(core_dir),
        "functions": {n: {"file": info[n]["file"], "md5": info[n]["md5"], "inputs": info[n]["params"],
                          "outputs": info[n]["outs"], "override": bool(info[n].get("override")),
                          "accelerated": bool(info[n].get("accelerated"))}
                      for n in names if n in info and n != "_notes"},
        "not_translated": failed,
        "required": sorted(required),
    }
    with open(os.path.join(tmp, "manifest.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(man, f, indent=1)
    if os.path.isdir(out_dir):
        shutil.rmtree(out_dir)
    os.replace(tmp, out_dir)
    return man


def promote(src, dst):
    """Make the checked package `src` the live one (`dst`)."""
    if not os.path.isdir(src):
        print("nothing to install: %s does not exist" % src)
        return 2
    if os.path.isdir(dst):
        shutil.rmtree(dst)
    os.replace(src, dst)
    print("installed %s" % dst)
    return 0


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if argv and argv[0] == "--promote":
        return promote(argv[1], argv[2])
    if argv and argv[0] == "--stamp-accel":
        stamp_accelerators(argv[1], argv[2])
        return 0
    ap = argparse.ArgumentParser()
    ap.add_argument("--core", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--overrides")
    ap.add_argument("--accel")
    ap.add_argument("--require", default="")
    ap.add_argument("--json")
    ns = ap.parse_args(argv)
    required = [r.strip() for r in ns.require.split(",") if r.strip()]
    modules, info, failed = translate_all(ns.core, ns.overrides, ns.accel)
    result = {"translated": sorted(modules), "failed": failed, "required_missing": [], "out": ns.out}
    missing = [r for r in required if r not in modules]
    result["required_missing"] = missing
    ok = not missing
    if ok:
        write_package(ns.out, modules, info, failed, ns.core, required)
    print("m2py: %d function file(s) translated, %d not translated." % (len(modules), len(failed)))
    for n, why in sorted(failed.items()):
        print("   not translated:", why)
    for n in sorted(k for k, v in info.items() if k != "_notes" and v.get("accelerated")):
        print("   accelerated   :", n)
    for note in info.get("_notes", []):
        print("   NOTE:", note)
    if missing:
        print("m2py: REQUIRED function(s) missing: %s. The existing Python core was NOT changed." % ", ".join(missing))
    else:
        print("m2py: wrote %s" % ns.out)
    if ns.json:
        with open(ns.json, "w", encoding="utf-8") as f:
            json.dump(result, f, indent=1)
    return 0 if ok else 2


if __name__ == "__main__":
    sys.exit(main())
